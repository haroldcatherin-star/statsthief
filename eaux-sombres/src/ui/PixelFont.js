export const ICON = { sun: '\u0001', moon: '\u0002', port: '\u0003', right: '\u0004', left: '\u0005', coin: '\u0006', fish: '\u0007', trap: '\u0008' };

const ACCENTS = {
  acute: ['...#.', '..#..'],
  grave: ['.#...', '..#..'],
  circ: ['..#..', '.#.#.'],
  diaer: ['.....', '.#.#.'],
};

const COMPOSED = {
  'É': ['E', 'acute'], 'È': ['E', 'grave'], 'Ê': ['E', 'circ'], 'Ë': ['E', 'diaer'],
  'À': ['A', 'grave'], 'Â': ['A', 'circ'], 'Ä': ['A', 'diaer'],
  'Ç': ['C', 'cedil'],
  'Ù': ['U', 'grave'], 'Û': ['U', 'circ'], 'Ü': ['U', 'diaer'],
  'Ô': ['O', 'circ'], 'Ö': ['O', 'diaer'],
  'Î': ['I', 'circ'], 'Ï': ['I', 'diaer'],
};

export const GLYPH_W = 5;
export const GLYPH_H = 10;
export const ADVANCE = 6;
export const LINE_H = 11;

export class PixelFont {
  constructor() {
    const bitmaps = new Map();
    for (const [ch, s] of Object.entries(G)) bitmaps.set(ch, ['.....', '.....', ...s.split('|'), '.....']);
    for (const [ch, [base, acc]] of Object.entries(COMPOSED)) {
      const rows = bitmaps.get(base).slice();
      if (acc === 'cedil') rows[9] = '..#..';
      else { rows[0] = ACCENTS[acc][0]; rows[1] = ACCENTS[acc][1]; }
      bitmaps.set(ch, rows);
    }
    this.index = new Map();
    const chars = [...bitmaps.keys()];
    this.atlas = document.createElement('canvas');
    this.atlas.width = chars.length * GLYPH_W;
    this.atlas.height = GLYPH_H;
    const ctx = this.atlas.getContext('2d');
    ctx.fillStyle = '#fff';
    chars.forEach((ch, i) => {
      this.index.set(ch, i);
      const rows = bitmaps.get(ch);
      for (let y = 0; y < GLYPH_H; y++) {
        for (let x = 0; x < GLYPH_W; x++) {
          if (rows[y][x] === '#') ctx.fillRect(i * GLYPH_W + x, y, 1, 1);
        }
      }
    });
    this.tinted = new Map();
  }

  tint(color) {
    if (!this.tinted.has(color)) {
      const c = document.createElement('canvas');
      c.width = this.atlas.width;
      c.height = this.atlas.height;
      const ctx = c.getContext('2d');
      ctx.drawImage(this.atlas, 0, 0);
      ctx.globalCompositeOperation = 'source-in';
      ctx.fillStyle = color;
      ctx.fillRect(0, 0, c.width, c.height);
      this.tinted.set(color, c);
    }
    return this.tinted.get(color);
  }

  measure(text, scale = 1) {
    const lines = String(text).split('\n');
    return Math.max(...lines.map((l) => [...l].length)) * ADVANCE * scale - scale;
  }

  draw(ctx, text, x, y, color = '#e8e0c8', { shadow = true, align = 'left', scale = 1 } = {}) {
    const lines = String(text).toUpperCase().split('\n');
    const atlas = this.tint(color);
    const dark = shadow ? this.tint('#000000') : null;
    const fallback = this.index.get('?');
    lines.forEach((line, li) => {
      const chars = [...line];
      const w = chars.length * ADVANCE * scale - scale;
      let lx = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? x - w : x;
      const ly = y + li * LINE_H * scale;
      for (const ch of chars) {
        const i = this.index.has(ch) ? this.index.get(ch) : fallback;
        if (ch !== ' ') {
          if (dark) ctx.drawImage(dark, i * GLYPH_W, 0, GLYPH_W, GLYPH_H, lx + scale, ly + scale, GLYPH_W * scale, GLYPH_H * scale);
          ctx.drawImage(atlas, i * GLYPH_W, 0, GLYPH_W, GLYPH_H, lx, ly, GLYPH_W * scale, GLYPH_H * scale);
        }
        lx += ADVANCE * scale;
      }
    });
  }
}
